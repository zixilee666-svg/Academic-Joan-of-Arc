def seed_questions() -> int:
    """将125题写入数据库（幂等）。返回写入/更新条数。"""
    from .db import get_conn, migrate

    migrate()
    conn = get_conn()
    n = 0
    try:
        for q_number, domain, level, question_zh, strategy in QUESTIONS_125:
            conn.execute(
                """
                INSERT INTO questions_125 (q_number, domain, level, question_zh, strategy_note)
                VALUES (?, ?, ?, ?, ?)
                ON CONFLICT(q_number) DO UPDATE SET
                    domain=excluded.domain, level=excluded.level,
                    question_zh=excluded.question_zh, strategy_note=excluded.strategy_note
                """,
                (q_number, domain, level, question_zh, strategy),
            )
            n += 1
        conn.commit()
    finally:
        conn.close()
    return n
